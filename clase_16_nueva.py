import pandas as pd
import streamlit as st

st.title("Comparar horarios")

if "df" not in st.session_state or st.session_state.df is None:
  st.warning("Por favor, carga los datos primero en la página 'Explorar los datos'.")
  st.stop()

df_f = st.session_state.get("df_filtrado", st.session_state.df)
col_alq = st.session_state.get("col_alquileres", "alquileres_total")

# --- REQUISITO R6: Gráfico de promedios por hora ---
# Control 9 (st.color_picker)
color_barras = st.color_picker("Color de las barras", "#197A8D")

if not df_f.empty:
  # Agrupar por hora y calcular el promedio
  df_horas = df_f.groupby("hora")[col_alq].mean().reset_index()
  df_horas.columns = ["Hora del día", "Promedio"]

  # Gráfico de barras usando st.bar_chart con color personalizado
  st.bar_chart(df_horas.set_index("Hora del día"), color=color_barras)

  # Control 10 (st.checkbox)
  mostrar_tabla = st.checkbox("Mostrar tabla de promedios")
  if mostrar_tabla:
    st.dataframe(
        df_horas.style.format({"Promedio": "{:.2f}"}), use_container_width=True
    )

  st.markdown("---")

  # --- REQUISITO R7: Límite de alquileres por hora (Control 11 / num_input) ---
  limite_alquileres = st.number_input(
      "Límite de alquileres por hora", value=250, step=10
  )

  # Filtrar horas cuyo promedio es estrictamente mayor que el límite
  horas_superiores = df_horas[df_horas["Promedio"] > limite_alquileres]
  total_horas_datos = len(df_horas)
  cant_superiores = len(horas_superiores)

  st.markdown("### Horarios con promedio mayor que el límite")
  st.markdown(f"## {cant_superiores}/{total_horas_datos}")

  if cant_superiores > 0:
    lista_horas_str = ", ".join(
        [f"{int(h):02d}:00" for h in horas_superiores["Hora del día"]]
    )
    st.markdown(f"Horarios: {lista_horas_str}.")
  else:
    st.markdown("Horarios: Ninguno.")

else:
  st.info("No hay registros disponibles para los filtros seleccionados.")